"""Phase 0, automated: can this machine run the whole pipeline?

    python cluster/preflight.py                        # report to stdout
    python cluster/preflight.py --write runs/hardware_notes.md
    python cluster/preflight.py --require-gpu          # non-zero exit if not ready

Run this FIRST on any cluster, before any job is submitted. It answers the
questions PIPELINE.md phase 0 asks, and it answers them from the machine
rather than from assumption:

  * How many GPUs, how much VRAM each, which compute capability?
  * Does bf16 actually work here? (Turing / sm_75 has no native bf16, and the
    shipped config says precision "32" on that expectation -- confirm it.)
  * Are the optimised Boltz attention kernels usable, or is --no_kernels
    required?
  * Are RFdiffusion, LigandMPNN and Boltz-2 all reachable from the paths in
    config/pipeline.yaml?

THE QUESTION THIS TOOL EXISTS TO ANSWER
---------------------------------------

The search is a closed loop: a cycle cannot pick its next frontier until the
designs it produced have been scored, which means generation and folding must
run on the SAME machine. RUNLOG.md records RFD3 and LigandMPNN on the AWS
cluster and Boltz-2 on Euler -- a split that this pipeline cannot drive,
because every cycle would need a round trip between two clusters.

So before anything else: run this on each candidate machine and pick the one
where all three tools are present. See cluster/README.md.

Exit codes: 0 all required checks passed; 1 something required is missing.
"""

from __future__ import annotations

import argparse
import os
import platform
import shutil
import socket
import subprocess
import sys
from dataclasses import dataclass, field
from datetime import datetime, timezone
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

OK = "PASS"
WARN = "WARN"
FAIL = "FAIL"


@dataclass
class Check:
    name: str
    status: str
    detail: str
    advice: str = ""
    required: bool = True


@dataclass
class Report:
    checks: list[Check] = field(default_factory=list)

    def add(self, *args, **kwargs) -> None:
        self.checks.append(Check(*args, **kwargs))

    @property
    def failed(self) -> list[Check]:
        return [c for c in self.checks if c.status == FAIL and c.required]

    def to_markdown(self, host: str) -> str:
        lines = [
            "# Hardware notes",
            "",
            f"Generated by `cluster/preflight.py` on {datetime.now(timezone.utc).isoformat()}",
            f"on host `{host}`.",
            "",
            "This file is phase 0's output. PIPELINE.md says to settle whether bf16",
            "works on sm_75 and whether `--no_kernels` is required, and to write the",
            "findings here rather than assume them.",
            "",
            "| Check | Status | Detail |",
            "| --- | --- | --- |",
        ]
        for c in self.checks:
            detail = c.detail.replace("|", "\\|").replace("\n", " ")
            lines.append(f"| {c.name} | **{c.status}** | {detail} |")
        advice = [c for c in self.checks if c.advice and c.status != OK]
        if advice:
            lines += ["", "## What to do", ""]
            for c in advice:
                lines.append(f"- **{c.name}** ({c.status}): {c.advice}")
        lines += [
            "",
            "## Still to do by hand",
            "",
            "This tool cannot answer phase 0's most important question: whether the",
            "geometry terms carry signal or are mostly Boltz-2 prediction noise. That",
            "needs the ten-seed control --- one fixed sequence, ten Boltz-2 seeds, all",
            "three score terms on each output. If the geometry sub-score's standard",
            "deviation across seeds is more than about half the spread between",
            "genuinely different designs, raise `run.eval_replicates` to 3 and",
            "`run.patience` to 4 before starting a real search.",
            "",
        ]
        return "\n".join(lines)


