def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--pipeline", default="config/pipeline.yaml")
    parser.add_argument(
        "--target", default="config/targets/01_his_asp.yaml",
        help="a target to cross-validate; pass '' to skip",
    )
    parser.add_argument("--write", metavar="PATH", help="also write a markdown report")
    parser.add_argument(
        "--require-gpu", action="store_true",
        help="treat a missing GPU as a failure (use inside a GPU job)",
    )
    args = parser.parse_args()

    host = socket.gethostname()
    report = Report()

    report.add("host", OK, f"{host} ({platform.platform()})", required=False)
    check_python(report)
    check_cpu_deps(report)
    pipeline = check_config(
        report,
        ROOT / args.pipeline,
        (ROOT / args.target) if args.target else None,
    )
    check_gpus(report, args.require_gpu)
    check_tools(report, pipeline)
    check_write_access(report)
    check_line_endings(report)

    width = max(len(c.name) for c in report.checks)
    print()
    for c in report.checks:
        print(f"  {c.status:<4}  {c.name:<{width}}  {c.detail}")
    print()

    advice = [c for c in report.checks if c.advice and c.status != OK]
    if advice:
        print("What to do:")
        for c in advice:
            print(f"  - {c.name}: {c.advice}")
        print()

    if args.write:
        out = Path(args.write)
        if not out.is_absolute():
            out = ROOT / out
        out.parent.mkdir(parents=True, exist_ok=True)
        out.write_text(report.to_markdown(host), encoding="utf-8")
        print(f"wrote {out}")

    failed = report.failed
    if failed:
        print(f"NOT READY: {len(failed)} required check(s) failed: "
              + ", ".join(c.name for c in failed))
        return 1
    print("PREFLIGHT PASSED")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
