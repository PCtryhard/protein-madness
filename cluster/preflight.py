def check_python(report: Report) -> None:
    version = sys.version.split()[0]
    major, minor = sys.version_info[:2]
    if (major, minor) >= (3, 10):
        report.add("python", OK, f"{version} at {sys.executable}")
    else:
        report.add(
            "python", FAIL, f"{version}",
            "the code uses `X | Y` type syntax and needs Python 3.10 or newer",
        )


def check_cpu_deps(report: Report) -> None:
    missing = []
    for module in ("numpy", "yaml", "pydantic"):
        try:
            __import__(module)
        except ImportError:
            missing.append(module)
    if missing:
        report.add(
            "cpu dependencies", FAIL, f"missing: {', '.join(missing)}",
            "pip install -r env/requirements.txt",
        )
    else:
        report.add("cpu dependencies", OK, "numpy, pyyaml, pydantic importable")


def check_config(report: Report, pipeline_path: Path, target_path: Path | None) -> object:
    try:
        from src.config import load_pipeline
    except Exception as exc:  # noqa: BLE001
        report.add("config import", FAIL, f"{type(exc).__name__}: {exc}",
                   "run this from the repo root")
        return None
    try:
        pipeline = load_pipeline(pipeline_path)
    except Exception as exc:  # noqa: BLE001
        report.add("config/pipeline.yaml", FAIL, f"{type(exc).__name__}: {exc}")
        return None
    report.add("config/pipeline.yaml", OK, f"loaded from {pipeline_path}")

    if target_path is not None:
        try:
            from src.config import load
            load(pipeline_path, target_path)
            report.add("target", OK, f"{target_path} cross-validates")
        except Exception as exc:  # noqa: BLE001
            report.add("target", FAIL, f"{target_path}: {exc}")
    return pipeline


def check_gpus(report: Report, require_gpu: bool) -> None:
    try:
        import torch
    except ImportError:
        report.add(
            "torch", FAIL if require_gpu else WARN, "not installed",
            "torch is not in env/requirements.txt on purpose: each model stack "
            "pins its own CUDA build. Install it the way the chosen cluster's "
            "setup script does.",
            required=require_gpu,
        )
        return

    report.add("torch", OK, torch.__version__)

    if not torch.cuda.is_available():
        report.add(
            "cuda", FAIL if require_gpu else WARN, "torch.cuda.is_available() is False",
            "on Euler you must be inside a GPU job (srun --gpus=1); on a login "
            "node this is expected and fine.",
            required=require_gpu,
        )
        return

    count = torch.cuda.device_count()
    configured = _configured_gpus()
    detail = []
    capabilities = set()
    for index in range(count):
        props = torch.cuda.get_device_properties(index)
        gib = props.total_memory / (1024 ** 3)
        capability = f"{props.major}.{props.minor}"
        capabilities.add((props.major, props.minor))
        detail.append(f"[{index}] {props.name}, {gib:.1f} GiB, sm_{props.major}{props.minor}")
    report.add("gpus", OK, "; ".join(detail))

    if configured is not None and count < len(configured):
        report.add(
            "run.gpus", FAIL,
            f"config asks for {configured} but only {count} device(s) are visible",
            f"set run.gpus to the devices that exist, e.g. {list(range(count))}",
        )
    else:
        report.add("run.gpus", OK, f"config asks for {configured}, {count} visible")

    # VRAM per card against the Boltz-2 reality.
    smallest = min(
        torch.cuda.get_device_properties(i).total_memory for i in range(count)
    ) / (1024 ** 3)
    if smallest < 10.0:
        report.add(
            "vram", FAIL, f"smallest card is {smallest:.1f} GiB",
            "Boltz-2 needs roughly 10 GB for a ~270 token system. Every model "
            "instance must fit inside ONE card: there is no sharding.",
        )
    elif smallest < 16.0:
        report.add(
            "vram", WARN, f"smallest card is {smallest:.1f} GiB",
            "tight but expected. Cut boltz.diffusion_samples first, then "
            "recycling_steps, then system size.",
            required=False,
        )
    else:
        report.add("vram", OK, f"smallest card is {smallest:.1f} GiB")

    _check_bf16(report, capabilities)


def _check_bf16(report: Report, capabilities: set[tuple[int, int]]) -> None:
    """Settle bf16 rather than assume it. PIPELINE.md asks for exactly this."""
    import torch

    turing = {c for c in capabilities if c < (8, 0)}
    try:
        supported = bool(torch.cuda.is_bf16_supported())
    except Exception:  # noqa: BLE001
        supported = False

    works = False
    error = ""
    if supported:
        try:
            a = torch.ones(8, 8, dtype=torch.bfloat16, device="cuda")
            works = bool(torch.isfinite((a @ a).float()).all().item())
        except Exception as exc:  # noqa: BLE001
            error = f"{type(exc).__name__}: {exc}"

    configured = _configured_precision()
    if works:
        report.add(
            "bf16", OK,
            f"usable (a bf16 matmul ran); torch reports supported={supported}",
            f"boltz.precision is {configured!r}. bf16 is available here, so "
            "'bf16' is a real option -- but confirm Boltz accepts it before "
            "changing it.",
            required=False,
        )
    else:
        why = error or f"torch.cuda.is_bf16_supported() = {supported}"
        detail = f"NOT usable ({why})"
        if turing:
            detail += f"; compute capability {sorted(turing)} has no native bf16"
        status = OK if configured != "bf16" else FAIL
        report.add(
            "bf16", status, detail,
            f"boltz.precision is {configured!r}, which is correct for this "
            "machine -- leave it."
            if configured != "bf16"
            else "boltz.precision is 'bf16' but bf16 does not work here. Set it "
                 'to "32".',
        )

    if turing:
        report.add(
            "boltz kernels", WARN,
            f"compute capability {sorted(turing)} predates Ampere; the optimised "
            "attention kernels Boltz ships target Ampere and later",
            "keep boltz.no_kernels: true. The only way to be sure is one real "
            "prediction with it false; if that works, turn it off for the speed.",
            required=False,
        )
    else:
        report.add(
            "boltz kernels", OK,
            "Ampere or newer; the optimised kernels should work",
            "try boltz.no_kernels: false for a speedup, and verify one "
            "prediction before trusting it.",
            required=False,
        )


def _configured_gpus() -> list[int] | None:
    try:
        from src.config import load_pipeline
        return load_pipeline(ROOT / "config" / "pipeline.yaml").run.gpus
    except Exception:  # noqa: BLE001
        return None


def _configured_precision() -> str:
    try:
        from src.config import load_pipeline
        return load_pipeline(ROOT / "config" / "pipeline.yaml").boltz.precision
    except Exception:  # noqa: BLE001
        return "?"


def check_tools(report: Report, pipeline) -> None:
    """Are all three model stacks reachable from here?

    This is the check that decides which cluster can run the loop at all.
    """
    if pipeline is None:
        return

    rfd = Path(os.path.expanduser(pipeline.rfdiffusion.run_inference))
    if rfd.exists():
        report.add("rfdiffusion", OK, str(rfd))
    else:
        report.add(
            "rfdiffusion", FAIL, f"not found: {rfd}",
            "set rfdiffusion.run_inference in config/pipeline.yaml to this "
            "cluster's run_inference.py",
        )

    mpnn = Path(os.path.expanduser(pipeline.ligandmpnn.run_script))
    if mpnn.exists():
        report.add("ligandmpnn", OK, str(mpnn))
    else:
        report.add(
            "ligandmpnn", FAIL, f"not found: {mpnn}",
            "set ligandmpnn.run_script in config/pipeline.yaml",
        )

    boltz = shutil.which(pipeline.boltz.binary)
    if boltz:
        version = _probe_boltz(boltz)
        report.add("boltz", OK, f"{boltz}{version}")
    else:
        report.add(
            "boltz", FAIL, f"{pipeline.boltz.binary!r} is not on PATH",
            "pip install boltz in the environment the jobs use, or set "
            "boltz.binary to its absolute path",
        )

    cache = Path(os.path.expanduser(pipeline.boltz.cache_dir))
    if cache.exists() and any(cache.iterdir()):
        report.add("boltz weights", OK, f"{cache} is populated", required=False)
    else:
        report.add(
            "boltz weights", WARN, f"{cache} is missing or empty",
            "Boltz downloads weights on first use. On Euler COMPUTE NODES HAVE "
            "NO OUTBOUND INTERNET, so do one prediction on the login node first "
            "to populate the cache, or the first job will hang or fail.",
            required=False,
        )


def _probe_boltz(binary: str) -> str:
    try:
        proc = subprocess.run(
            [binary, "--help"], capture_output=True, text=True, timeout=120, check=False
        )
    except (OSError, subprocess.TimeoutExpired) as exc:
        return f"  (could not run --help: {type(exc).__name__})"
    if proc.returncode != 0:
        return "  (--help exited non-zero)"
    flags = []
    for flag in ("--no_kernels", "--diffusion_samples", "--recycling_steps",
                 "--sampling_steps", "--write_full_pae", "--output_format"):
        if flag in proc.stdout:
            flags.append(flag)
    missing = [f for f in ("--no_kernels", "--diffusion_samples", "--write_full_pae")
               if f not in proc.stdout]
    note = f"  (accepts {len(flags)} of the flags we pass"
    if missing:
        note += f"; MISSING {', '.join(missing)}"
    return note + ")"


def check_write_access(report: Report) -> None:
    runs = ROOT / "runs"
    try:
        runs.mkdir(exist_ok=True)
        probe = runs / ".preflight_write_test"
        probe.write_text("ok", encoding="utf-8")
        probe.unlink()
        report.add("runs/ writable", OK, str(runs))
    except OSError as exc:
        report.add("runs/ writable", FAIL, f"{runs}: {exc}",
                   "the run directory holds designs.db and every structure")


def check_line_endings(report: Report) -> None:
    """CRLF in a submission script is a real failure recorded in RUNLOG.md."""
    # Only the directories whose scripts actually get submitted. data/ holds
    # archived inputs from past runs (one of which does have CRLF -- that is
    # the very failure RUNLOG.md section 4 records), and outdated/ is not
    # maintained; flagging either would train people to ignore this check.
    offenders = []
    for directory in ("cluster", "scripts", "env"):
        base = ROOT / directory
        if not base.exists():
            continue
        for pattern in ("*.sh", "*.sbatch", "*.bash"):
            for path in base.rglob(pattern):
                if b"\r\n" in path.read_bytes():
                    offenders.append(path.relative_to(ROOT).as_posix())
    if offenders:
        report.add(
            "script line endings", FAIL, f"CRLF found in: {', '.join(offenders)}",
            "sbatch rejects CRLF scripts and the error does not say so "
            "(RUNLOG.md section 4). Fix with: sed -i 's/\\r$//' <file>. "
            ".gitattributes should prevent this.",
        )
    else:
        report.add("script line endings", OK, "all LF")


