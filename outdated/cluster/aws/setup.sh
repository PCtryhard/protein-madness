#!/bin/bash
# Set up this pipeline on the provided AWS cluster (the 2-GPU box where RFD3
# and LigandMPNN live). Idempotent.
#
#   ssh <user>@<aws-host>
#   git clone <repo> && cd protein-madness
#   bash cluster/aws/setup.sh
#   source ~/protein-madness-env/activate.sh
#   python cluster/preflight.py --require-gpu --write runs/hardware_notes.md
#
# What this script does NOT do: install RFdiffusion, LigandMPNN or their
# weights. Those are provided on this cluster already -- RUNLOG.md section 1
# records `bash /mnt/ref/hackathon/setup.sh` doing it, and the earlier runs
# used tools under /mnt/ref and wrote to /mnt/work. This script builds the
# Python environment THIS pipeline needs on top of that, and then tells you
# which paths to put in config/pipeline.yaml.
#
# Unlike Euler there is no SLURM here: run the searches with
# cluster/aws/run_all.sh, which keeps two going at a time, one per card.
set -euo pipefail

REPO_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")/../.." && pwd)"
VENV_DIR="${PM_VENV:-$HOME/protein-madness-env}"
ACTIVATE="$VENV_DIR/activate.sh"

# Where the provided tooling lives on this cluster, per RUNLOG.md. These are
# starting guesses for the search below, not assertions.
REF_ROOTS=("/mnt/ref/hackathon" "/mnt/ref" "/mnt/work" "$HOME")

TORCH_VERSION="${PM_TORCH:-2.5.1}"
TORCH_INDEX="${PM_TORCH_INDEX:-https://download.pytorch.org/whl/cu121}"

log() { printf '[aws setup] %s\n' "$*"; }
die() { printf '[aws setup] ERROR: %s\n' "$*" >&2; exit 1; }

[ -f "$REPO_DIR/env/requirements.txt" ] \
    || die "cannot find $REPO_DIR/env/requirements.txt"

# ---------------------------------------------------------------- python

PYTHON_BIN="${PM_PYTHON_BIN:-}"
if [ -z "$PYTHON_BIN" ]; then
    for candidate in python3.12 python3.11 python3.10 python3; do
        if command -v "$candidate" >/dev/null 2>&1; then
            PYTHON_BIN="$(command -v "$candidate")"
            break
        fi
    done
fi
[ -n "$PYTHON_BIN" ] || die "no python3 found on PATH"

# The code uses `X | Y` type syntax, so 3.10 is the floor.
"$PYTHON_BIN" - <<'PY' || die "python is older than 3.10; set PM_PYTHON_BIN to a newer one"
import sys
raise SystemExit(0 if sys.version_info[:2] >= (3, 10) else 1)
PY
log "python: $PYTHON_BIN ($("$PYTHON_BIN" --version 2>&1))"

# ---------------------------------------------------------------- venv

if [ -x "$VENV_DIR/bin/python" ]; then
    log "venv exists: $VENV_DIR (reusing)"
else
    log "creating venv: $VENV_DIR"
    "$PYTHON_BIN" -m venv "$VENV_DIR"
fi
set +u; . "$VENV_DIR/bin/activate"; set -u

python -m pip install --upgrade pip setuptools wheel
log "installing env/requirements.txt (pinned)"
python -m pip install -r "$REPO_DIR/env/requirements.txt"

if python -c "import torch" >/dev/null 2>&1; then
    log "torch already installed: $(python -c 'import torch; print(torch.__version__)')"
else
    log "installing torch==$TORCH_VERSION from $TORCH_INDEX"
    python -m pip install "torch==$TORCH_VERSION" --index-url "$TORCH_INDEX"
fi

if python -c "import boltz" >/dev/null 2>&1; then
    log "boltz already installed"
else
    log "installing boltz"
    python -m pip install boltz \
        || log "WARNING: boltz install failed. If Boltz-2 is not available on
         this cluster, see cluster/README.md -- the loop cannot run split
         across two clusters, so this matters."
fi

# ---------------------------------------------------------------- find tools

# Report what is actually here rather than guessing. preflight.py checks the
# configured paths; this just helps you fill them in.
log "looking for the provided tools (this can take a moment)"

find_one() {
    local pattern="$1"
    local root
    for root in "${REF_ROOTS[@]}"; do
        [ -d "$root" ] || continue
        local hit
        hit="$(find "$root" -maxdepth 6 -name "$pattern" -type f 2>/dev/null | head -1)"
        if [ -n "$hit" ]; then printf '%s\n' "$hit"; return 0; fi
    done
    return 1
}

RFD_PATH="$(find_one 'run_inference.py' || true)"
MPNN_PATH="$(find_one 'run.py' || true)"
BOLTZ_PATH="$(command -v boltz || true)"

# ---------------------------------------------------------------- activate.sh

log "writing $ACTIVATE"
cat > "$ACTIVATE" <<EOF
#!/bin/bash
# GENERATED by cluster/aws/setup.sh on $(date -Is). Do not edit; re-run setup.
set +u
. "$VENV_DIR/bin/activate"
set -u
export PYTHONPATH="$REPO_DIR\${PYTHONPATH:+:\$PYTHONPATH}"
export BOLTZ_CACHE="\${BOLTZ_CACHE:-\$HOME/.boltz}"
# Leave CUDA_VISIBLE_DEVICES alone: the pipeline's own worker pool pins one
# card per design and sets it per subprocess.
EOF
chmod +x "$ACTIVATE"

# ---------------------------------------------------------------- report

log "done."
cat <<EOF

  Environment : $VENV_DIR
  Activate    : source "$ACTIVATE"
  Repo        : $REPO_DIR

  Put these in config/pipeline.yaml (verify them -- they are search results,
  not promises):

    rfdiffusion.run_inference : ${RFD_PATH:-NOT FOUND -- locate run_inference.py yourself}
    ligandmpnn.run_script     : ${MPNN_PATH:-NOT FOUND -- locate LigandMPNN run.py yourself}
    boltz.binary              : ${BOLTZ_PATH:-NOT FOUND -- boltz is not on PATH}

  NOTE on ligandmpnn: 'run.py' is a common filename, so the hit above may
  belong to something else entirely. Check it before trusting it.

  Then, in order:

    source "$ACTIVATE"
    python cluster/preflight.py --require-gpu --write runs/hardware_notes.md
    bash cluster/aws/run_all.sh --dry-run
    bash cluster/aws/run_all.sh

EOF
